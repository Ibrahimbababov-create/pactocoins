-- Отдельная метка: какой ранг пользователю уже показали в
-- полноэкранной анимации. Отличается от last_level_id, который
-- выставляется на стороне сервера в момент одобрения начисления —
-- ещё до того, как человек откроет приложение.
alter table public.users
  add column celebrated_level_id integer not null default 1;

-- Бэкфилл: не устраивать ретроспективный праздник тем, кто уже
-- давно прошёл несколько рангов — считаем, что их текущий ранг
-- уже "показан", анимацию увидят только при следующем повышении.
update public.users set celebrated_level_id = greatest(last_level_id, 1);
